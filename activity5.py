# + - addition
# - - subtraction
# * - multiplication
# / - division
# // - floor division
# ** - exponentation
# % - modulus

a = int(input("Enter a number --> "))
b = int(input("Enter a number --> "))

print("The sum of a + b is ", a+b)
print("The sum of a - b is ",a-b)
print("The sum of a * b is ", a*b)
print("The sum of a / b is ", a/b)
print("The sum of a // b is ", a//b)
print("The sum of a ** b is ", a**b)
print("The sum of a % b is ", a%b)
